#!/usr/bin/env nix-shell
#!nix-shell -i bash -p gh jq gnupatch
#!nix-shell -p "(builtins.getFlake \"github:sempruijs/json2nix\").packages.${builtins.currentSystem}.default"
# Generate masa/versions.nix, the MasaCMS pins masa/definitions.nix reads.
#
# Dependencies come from the nix-shell shebang; gh must be logged in. If it
# is not:
#   nix run nixpkgs#gh -- auth login
#
# Usage:
#   ./tools/update-masa.sh --list              # list the stable tags on GitHub
#   ./tools/update-masa.sh 7.6.2 7.5.7 ...     # print pins for these tags
#   ./tools/update-masa.sh                     # print pins for the default set:
#                                              # every stable tag >= 7.2, plus
#                                              # the last 7.1 build
#
# Prints the finished Nix to stdout; redirect it into masa/versions.nix
# yourself (merge by hand when pinning single tags). Deliberately not
# self-writing. Each tag is prefetched into the store to get its hash and to
# decide which of masa/patches/ it needs; a patch whose target exists but which
# does not apply is reported loudly.
set -euo pipefail

REPO="MasaCMS/MasaCMS"

# Authenticated through gh: unauthenticated GitHub API calls (tag listing, and
# nix resolving github: refs) run into the rate limit long before ~70 tags.
GH_TOKEN="$(gh auth token)"
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
PATCHES="$ROOT/masa/patches"

stable_tags() {
  gh api --paginate "repos/$REPO/tags" --jq '.[].name' |
    grep -E '^[0-9]+(\.[0-9]+)+$' | sort -V
}

if [[ "${1:-}" == "--list" ]]; then
  stable_tags
  exit 0
fi

if [[ $# -gt 0 ]]; then
  tags=("$@")
else
  mapfile -t all < <(stable_tags)
  tags=()
  last71=""
  for t in "${all[@]}"; do
    case "$t" in
      7.1.*) last71=$t ;;
      7.0* | [0-6].*) ;;
      *) tags+=("$t") ;;
    esac
  done
  tags=("$last71" "${tags[@]}")
fi

# Which patches a tree needs: the queryToStruct one only where the method is
# still declared.
needs_patches() {
  local src=$1
  if grep -q 'function queryToStruct( qry )' "$src/core/mura/utility.cfc" 2>/dev/null; then
    echo masa-utility-querytostruct.patch
  fi
}

pin() {
  local tag=$1 json src hash p patches=()
  echo "==> $tag" >&2
  json=$(nix flake prefetch --json --option access-tokens "github.com=$GH_TOKEN" "github:$REPO/$tag")
  src=$(jq -r .storePath <<<"$json")
  hash=$(jq -r .hash <<<"$json")
  while IFS= read -r p; do
    [[ -n "$p" ]] || continue
    if ! patch -p1 -d "$src" --dry-run --silent <"$PATCHES/$p" >/dev/null 2>&1; then
      echo "ERROR: $p is needed by $tag but does not apply - refresh it" >&2
      exit 1
    fi
    patches+=("$p")
  done < <(needs_patches "$src")
  jq -n --arg v "$tag" --arg h "$hash" '{($v): {hash: $h, patches: $ARGS.positional}}' \
    --args "${patches[@]}"
}

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
for t in "${tags[@]}"; do pin "$t"; done | jq -s 'add' >"$tmp/versions.json"

# json2nix is interactive: it asks for the input and the output file name.
printf '%s\n%s\n' "$tmp/versions.json" "$tmp/versions.nix" |
  json2nix >/dev/null

# Through the flake's formatter (self.formatter), as if it were masa/versions.nix.
{
  echo "# MasaCMS pins: version -> source hash + the masa/patches/ it needs."
  echo "# Generated by tools/update-masa.sh (see doc/updating.md)."
  cat "$tmp/versions.nix"
  echo
} | (cd "$ROOT" && nix fmt -- --stdin masa/versions.nix)
